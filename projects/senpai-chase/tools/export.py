# Generates senpai/assets.h: background 320x240 + man and girl frames in RGB565
# (bytes already swapped for direct sending to the display; KEY = transparent)
import math, random, sys, os
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

sys.path.insert(0, os.path.dirname(__file__))
import make_man, make_girl

KEY = 0x1FF8  # magenta 0xF81F with bytes swapped

def rgb565s(arr):
    """arr (...,3) uint8 -> uint16 RGB565 with bytes swapped"""
    r = arr[..., 0].astype(np.uint16); g = arr[..., 1].astype(np.uint16); b = arr[..., 2].astype(np.uint16)
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    return ((v >> 8) | (v << 8)) & 0xFFFF

def sprite_data(im):
    """RGBA -> (w,h,ox,oy,data) trimmed to the bbox, transparent = KEY"""
    a = np.array(im)
    ys, xs = np.nonzero(a[..., 3] > 127)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    c = a[y0:y1, x0:x1]
    v = rgb565s(c[..., :3])
    v[v == KEY] = KEY ^ 0x0100
    v[c[..., 3] <= 127] = KEY
    return x1 - x0, y1 - y0, x0, y0, v.flatten()

def background():
    rnd = random.Random(7)
    W, H = 320, 240
    yy, xx = np.mgrid[0:H, 0:W]
    # grass with noise
    noise = np.zeros((H, W))
    for s, amp in ((40, 1.0), (16, 0.5), (6, 0.3), (2, 0.2)):
        g = np.random.RandomState(s).rand(H // s + 2, W // s + 2)
        noise += amp * np.array(Image.fromarray((g * 255).astype(np.uint8)).resize((W + 2 * s, H + 2 * s), Image.BICUBIC))[s:s + H, s:s + W] / 255
    noise /= 2.0
    base = np.array((96, 176, 88)) * (0.82 + 0.3 * noise[..., None])
    img = Image.fromarray(np.clip(base, 0, 255).astype(np.uint8))
    d = ImageDraw.Draw(img)
    # curved stone path
    pts = [(-20, 180), (60, 165), (140, 140), (200, 150), (260, 120), (340, 100)]
    for i in range(len(pts) - 1):
        d.line([pts[i], pts[i + 1]], fill=(206, 186, 150), width=34, joint="curve")
    for i in range(len(pts)):
        d.ellipse([pts[i][0] - 17, pts[i][1] - 17, pts[i][0] + 17, pts[i][1] + 17], fill=(206, 186, 150))
    arr = np.array(img).astype(float)
    path = (np.abs(arr - (206, 186, 150)).sum(-1) < 3)
    # path stones
    for _ in range(260):
        x, y = rnd.randint(0, W - 1), rnd.randint(0, H - 1)
        if path[y, x]:
            r = rnd.randint(3, 6); c = rnd.randint(170, 215)
            d.ellipse([x - r, y - r * 0.7, x + r, y + r * 0.7], fill=(c, c - 14, c - 40), outline=(150, 132, 104))
    # flowers
    for _ in range(140):
        x, y = rnd.randint(0, W - 1), rnd.randint(70, H - 1)
        if not path[y, x]:
            col = rnd.choice([(255, 255, 255), (255, 220, 90), (255, 160, 200), (180, 160, 255)])
            d.point([(x, y), (x + 1, y), (x, y + 1), (x - 1, y), (x, y - 1)], fill=col)
            d.point([(x, y)], fill=(255, 210, 60))
    # pond bottom-right
    d.ellipse([228, 168, 330, 236], fill=(70, 120, 110))
    d.ellipse([234, 172, 330, 232], fill=(90, 160, 200))
    d.ellipse([250, 180, 300, 200], fill=(140, 200, 235))
    for x, y in ((262, 214), (290, 186)):
        d.ellipse([x - 6, y - 4, x + 6, y + 4], fill=(70, 150, 70)); d.point([(x + 2, y - 1)], fill=(255, 170, 210))
    # cherry trees (sakura) along the top edge
    for tx, ty, r in ((30, 18, 34), (105, 4, 30), (175, 22, 36), (250, 0, 32), (308, 30, 28)):
        d.ellipse([tx - r * 0.9, ty + r * 0.5, tx + r * 0.9, ty + r * 1.15], fill=(60, 110, 60))  # shadow
        d.rectangle([tx - 4, ty + 8, tx + 4, ty + r * 0.85], fill=(110, 70, 55))
        for k in range(40):
            a = rnd.random() * 6.28; rr = rnd.random() ** 0.5 * r * 0.85
            x, y = tx + math.cos(a) * rr, ty + math.sin(a) * rr * 0.75
            s = rnd.randint(7, 12)
            c = rnd.choice([(255, 183, 206), (250, 160, 190), (255, 205, 222), (235, 140, 175)])
            d.ellipse([x - s, y - s, x + s, y + s], fill=c)
        for k in range(14):
            a = rnd.random() * 6.28; rr = rnd.random() * r * 0.7
            x, y = tx + math.cos(a) * rr - 4, ty + math.sin(a) * rr * 0.6 - 6
            d.ellipse([x - 3, y - 3, x + 3, y + 3], fill=(255, 228, 238))
    # fallen petals on the grass
    for _ in range(220):
        x, y = rnd.randint(0, W - 1), rnd.randint(40, H - 1)
        d.point([(x, y), (x + 1, y)], fill=rnd.choice([(255, 190, 210), (255, 215, 228)]))
    return img

def c_array(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append(",".join("0x%04X" % v for v in data[i:i + 16]))
    return "static const uint16_t %s[%d] = {\n%s\n};\n" % (name, len(data), ",\n".join(lines))

def main(out_h, cut_path, preview):
    bg = background()
    bg.save(preview + "_bg.png")
    out = ["// Generated by tools/export.py -- do not edit by hand", "#pragma once", "#include <stdint.h>",
           "#define KEY_COLOR 0x%04X" % KEY,
           "struct Frame { uint8_t w, h; int8_t ox, oy; const uint16_t *px; };"]
    out.append(c_array("BG", rgb565s(np.array(bg)).flatten()))
    # man
    right, left = make_man.all_frames(cut_path)
    entries = []
    for side, fr in (("R", right), ("L", left)):
        for i, f in enumerate(fr):
            w, h, ox, oy, v = sprite_data(f)
            nm = "MAN_%s%d" % (side, i)
            out.append(c_array(nm, v))
            # offset relative to the "feet" point: bottom center of the original image
            entries.append("{%d,%d,%d,%d,%s}" % (w, h, ox - make_man.W // 2, oy - (make_man.H - 3), nm))
    out.append("#define MAN_FRAMES %d" % len(right))
    out.append("static const Frame MAN[2][%d] = {{%s},{%s}};" % (len(right), ",".join(entries[:len(right)]), ",".join(entries[len(right):])))
    # girl
    frames = make_girl.all_frames()
    rows = []
    for d, fr in enumerate(frames):
        e = []
        for k, f in enumerate(fr):
            w, h, ox, oy, v = sprite_data(f)
            nm = "GIRL_%d_%d" % (d, k)
            out.append(c_array(nm, v))
            e.append("{%d,%d,%d,%d,%s}" % (w, h, ox - make_girl.W // 2, oy - make_girl.FOOT_Y, nm))
        rows.append("{" + ",".join(e) + "}")
    out.append("#define GIRL_FRAMES %d" % len(frames[0]))
    out.append("static const Frame GIRL[8][%d] = {%s};" % (len(frames[0]), ",\n".join(rows)))
    open(out_h, "w").write("\n".join(out) + "\n")
    sheet = Image.new("RGBA", (make_girl.W * 10, make_girl.H * 8), (90, 160, 90, 255))
    for r, row in enumerate(frames):
        for c, f in enumerate(row): sheet.alpha_composite(f, (c * make_girl.W, r * make_girl.H))
    sheet.save(preview + "_girl.png")
    print("ok", os.path.getsize(out_h))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3])
